def _normalize_gene_name(g):
    if pd.isna(g):
        return None
    g = str(g).strip().upper()
    g = re.sub(r"\s+", "", g)
    return g if g else None


def _coerce_profile_to_series(profile, profile_name="unknown_profile"):

    if profile is None:
        raise ValueError(f"{profile_name} is None")

    if isinstance(profile, pd.Series):
        s = profile.copy()

    elif isinstance(profile, dict):
        s = pd.Series(profile)

    elif isinstance(profile, pd.DataFrame):

        df = profile.copy()
        cols = {c.lower(): c for c in df.columns}

        gene_col = None
        value_col = None

        for c in ["gene", "genes", "symbol", "id"]:
            if c in cols:
                gene_col = cols[c]

        for c in ["average_expression","expression","value","avg","mean"]:
            if c in cols:
                value_col = cols[c]

        if gene_col and value_col:
            s = pd.Series(df[value_col].values, index=df[gene_col].values)

        elif df.shape[1] == 1:
            s = df.iloc[:,0]

        else:
            s = pd.Series(df.iloc[:,1].values, index=df.iloc[:,0].values)

    else:
        raise ValueError("Unsupported profile type")

    s = pd.to_numeric(s, errors="coerce")
    s = s[~s.isna()]

    new_index = [_normalize_gene_name(i) for i in s.index]
    s.index = new_index
    s = s[s.index.notna()]

    if s.index.duplicated().any():
        s = s.groupby(level=0).sum()

    return s.sort_index()


def _compute_distance(sample_s, ref_s, metric):

    common = sample_s.index.intersection(ref_s.index)

    if len(common) == 0:
        return np.nan

    x = sample_s.loc[common].values
    y = ref_s.loc[common].values

    if metric == "euclidean":
        return np.linalg.norm(x-y)

    if metric == "cosine":
        nx = np.linalg.norm(x)
        ny = np.linalg.norm(y)
        if nx==0 or ny==0:
            return np.nan
        return 1 - np.dot(x,y)/(nx*ny)

    if metric == "canberra":
        denom = np.abs(x)+np.abs(y)
        valid = denom!=0
        return np.sum(np.abs(x[valid]-y[valid])/denom[valid])

    if metric == "spearman":

        rx = pd.Series(x).rank().values
        ry = pd.Series(y).rank().values
        corr = np.corrcoef(rx,ry)[0,1]

        return 1-corr

    raise ValueError(metric)




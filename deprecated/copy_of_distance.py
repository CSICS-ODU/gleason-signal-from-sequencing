import numpy as np
from scipy.spatial.distance import canberra, cosine, euclidean
from scipy.stats import spearmanr


def compute_dist(a, b, metric):
    """
    Compute distance between two aligned numeric vectors.

    Supported metrics:
        - canberra
        - cosine
        - euclidean
        - spearman   (implemented as 1 - Spearman correlation)
    """
    if metric == "canberra":
        return canberra(a, b)
    elif metric == "cosine":
        return cosine(a, b)
    elif metric == "euclidean":
        return euclidean(a, b)
    elif metric == "spearman":
        coef, _ = spearmanr(a, b)
        return 1 - coef
    else:
        raise ValueError(f"Metric '{metric}' not recognized.")


def calculate_landscape_distance(
    overall_ref,
    high_gleason_ref,
    low_gleason_ref,
    candidate_profile,
    metric="canberra"
):
    """
    Measure distance from a candidate profile to three reference landscapes:
    overall, high-Gleason, and low-Gleason.

    Existing logic preserved:
    1. Find common genes across all four profiles.
    2. Extract aligned values.
    3. Normalize each vector so its values sum to 1 within the shared subspace.
    4. Compute candidate distance to overall, high, and low references.
    5. Return raw structured result, including the original prototype hypothesis block.
    """
    common_genes = sorted(
        set(overall_ref.keys())
        & set(high_gleason_ref.keys())
        & set(low_gleason_ref.keys())
        & set(candidate_profile.keys())
    )

    if not common_genes:
        raise ValueError("No overlapping genes found between references and candidate.")

    vals_overall = np.array([overall_ref[g] for g in common_genes], dtype=float)
    vals_high = np.array([high_gleason_ref[g] for g in common_genes], dtype=float)
    vals_low = np.array([low_gleason_ref[g] for g in common_genes], dtype=float)
    vals_candidate = np.array([candidate_profile[g] for g in common_genes], dtype=float)

    sum_overall = np.sum(vals_overall)
    sum_high = np.sum(vals_high)
    sum_low = np.sum(vals_low)
    sum_candidate = np.sum(vals_candidate)

    if sum_overall == 0 or sum_high == 0 or sum_low == 0 or sum_candidate == 0:
        raise ValueError("One or more aligned profiles sum to zero after subspace projection.")

    norm_overall = vals_overall / sum_overall
    norm_high = vals_high / sum_high
    norm_low = vals_low / sum_low
    norm_candidate = vals_candidate / sum_candidate

    d_overall = compute_dist(norm_overall, norm_candidate, metric)
    d_high = compute_dist(norm_high, norm_candidate, metric)
    d_low = compute_dist(norm_low, norm_candidate, metric)

    return {
    "d_all": d_overall,
    "d_high": d_high,
    "d_low": d_low,
    "n_genes": len(common_genes)
    }

def build_candidate_aggregate(
    metadata_df,
    samples_dir,
    master_genes,
    gleason_class="all",
    race=None,
    id_col="ID",
    gleason_group_col="gleason_class",
    race_col="race",
):
    """
    Build a cohort-level aggregate candidate profile in the same format as
    load_gene_profile(): {gene: value}.

    Selection is controlled by:
      - gleason_class: "high", "low", or "all"
      - race: "EA", "AA", "IN", or None

    The function:
      1. filters metadata rows,
      2. maps each selected ID to samples_dir/<ID>.csv,
      3. loads each profile using load_gene_profile(),
      4. projects each profile using project_profile_to_universe(),
      5. averages the projected profiles gene-wise.

    Returns:
      dict[str, float]
    """
    valid_gleason = {"high", "low", "all"}
    valid_races = {"EA", "AA", "IN", None}

    if gleason_class not in valid_gleason:
        raise ValueError(
            f"gleason_class must be one of {valid_gleason}, got {gleason_class!r}"
        )

    if race not in valid_races:
        raise ValueError(
            f"race must be one of {{'EA', 'AA', 'IN', None}}, got {race!r}"
        )

    if id_col not in metadata_df.columns:
        raise ValueError(f"Column {id_col!r} not found in metadata_df")

    if gleason_group_col not in metadata_df.columns:
        raise ValueError(f"Column {gleason_group_col!r} not found in metadata_df")

    if race is not None and race_col not in metadata_df.columns:
        raise ValueError(f"Column {race_col!r} not found in metadata_df")

    subset = metadata_df.copy()

    if gleason_class != "all":
        subset = subset[
            subset[gleason_group_col].astype(str).str.strip().str.lower() == gleason_class
        ]

    if race is not None:
        subset = subset[
            subset[race_col].astype(str).str.strip().str.upper() == race.upper()
        ]

    if subset.empty:
        raise ValueError(
            f"No metadata rows matched gleason_class={gleason_class!r}, race={race!r}"
        )

    sample_files = [
        os.path.join(samples_dir, f"{sample_id}.csv")
        for sample_id in subset[id_col].astype(str).str.strip().tolist()
        if os.path.exists(os.path.join(samples_dir, f"{sample_id}.csv"))
    ]

    if not sample_files:
        raise ValueError(
            f"No sample files found for gleason_class={gleason_class!r}, race={race!r}"
        )

    projected_profiles = []
    for sample_path in sample_files:
        profile = load_gene_profile(sample_path)
        projected_profile = project_profile_to_universe(profile, master_genes)
        projected_profiles.append(projected_profile)

    aggregate_profile = {}
    n = len(projected_profiles)

    for gene in master_genes:
        aggregate_profile[gene] = sum(p[gene] for p in projected_profiles) / n

    return aggregate_profile

def classify_gleason(gleason_value):
    """
    Convert raw Gleason score representation into 'high' or 'low'.

    Rules used for current dataset:
      >7  -> high
      <7  -> low
      3+4 -> low
      4+3 -> high
      7   -> low  / undecided : not implemented in current model
    """
    s = str(gleason_value).strip()

    if "4+3" in s:
        return "high"
    if "3+4" in s:
        return "low"

    try:
        g = int(s)
        if g > 7:
            return "high"
        else:
            return "low"
    except ValueError:
        raise ValueError(f"Unrecognized Gleason value: {gleason_value}")


def interpret_distance_result(candidate_profile, overall_ref, high_gleason_ref, low_gleason_ref, metric, expected_gleason_class=None):
    result = calculate_landscape_distance(overall_ref, high_gleason_ref, low_gleason_ref, candidate_profile, metric)
    d_all = result["d_all"]
    d_high = result["d_high"]
    d_low = result["d_low"]

    if expected_gleason_class == "high":
        result["hypothesis_tests"] = {"class_test": d_high < d_low, "all_test": d_high < d_all < d_low}
    elif expected_gleason_class == "low":
        result["hypothesis_tests"] = {"class_test": d_low < d_high, "all_test": d_low < d_all < d_high}
    else:
        result["hypothesis_tests"] = {"class_test": None, "all_test": None}

    return result

def print_hypothesis_result(h):
    if h["class_test"] is None:
        print("No ground truth label — hypothesis tests not evaluated.")
        return

    print("Hypothesis 1: Candidate should be closer to the correct class reference than the opposite class.")
    print("Result:", h["class_test"])

    print("Hypothesis 2: Candidate should lie between ALL and the opposite class reference.")
    print("Result:", h["all_test"])


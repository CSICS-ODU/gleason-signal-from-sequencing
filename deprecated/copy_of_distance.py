import os
import pandas as pd


def load_gene_profile(filepath, gene_col="gene", val_col="average_expression"):
    """
    Load a gene profile CSV into a {gene: value} dictionary.

    Behavior:
    - Uses `val_col` if present.
    - Otherwise falls back to:
        1. average_expression
        2. variant_count
    - Averages duplicate genes.
    - Drops rows with missing gene or missing value.
    """
    try:
        df = pd.read_csv(filepath)
    except UnicodeDecodeError:
        print(filepath)
        df = pd.read_csv(filepath, encoding="latin1")

    if gene_col not in df.columns:
        raise ValueError(f"Column '{gene_col}' not found in {filepath}")

    if val_col in df.columns:
        value_col = val_col
    elif "average_expression" in df.columns:
        value_col = "average_expression"
    elif "variant_count" in df.columns:
        value_col = "variant_count"
    else:
        raise ValueError(
            f"No usable value column found in {filepath}. "
            f"Expected one of: '{val_col}', 'average_expression', 'variant_count'."
        )

    work = df[[gene_col, value_col]].copy()
    work = work.dropna(subset=[gene_col, value_col])

    # Force numeric where possible, drop non-numeric rows
    work[value_col] = pd.to_numeric(work[value_col], errors="coerce")
    work = work.dropna(subset=[value_col])

    # Average duplicate genes
    grouped = work.groupby(gene_col, as_index=False)[value_col].mean()

    return dict(zip(grouped[gene_col], grouped[value_col]))


def build_master_gene_universe(sample_paths, gene_col="gene", val_col="average_expression"):
    """
    Build the master gene universe from a collection of sample files.

    Intended use:
    - Pass all 20 candidate sample paths here.
    - The returned universe is the UNION of all genes observed across them.

    Returns:
    - sorted list of genes
    """
    gene_universe = set()

    for path in sample_paths:
        profile = load_gene_profile(path, gene_col=gene_col, val_col=val_col)
        gene_universe.update(profile.keys())

    return sorted(gene_universe)


def project_profile_to_universe(profile, gene_universe, fill_value=0.0):
    """
    Project a {gene: value} profile onto a fixed gene universe.

    Missing genes are filled with `fill_value` (default 0.0).

    Returns:
    - dict with exactly the genes in `gene_universe`
    """
    return {gene: float(profile.get(gene, fill_value)) for gene in gene_universe}



def normalize_id(x):
    """
    Normalize either a metadata ID value or a filename/path into a canonical ID.

    Supported canonical outputs:
    - PT<number>   e.g. PT495
    - <digits>     e.g. 50702111163
    """
    if x is None:
        return None

    s = str(x).strip()
    s = os.path.basename(s)

    # Remove .csv extension if present
    s = re.sub(r"\.csv$", "", s, flags=re.IGNORECASE)

    # Case 1: plain numeric ID
    if re.fullmatch(r"\d+", s):
        return s

    # Case 2: PT-style ID already present
    m = re.fullmatch(r"PT[_-]?(\d+)", s, flags=re.IGNORECASE)
    if m:
        return f"PT{m.group(1)}"

    # Case 3: embedded patterns like sample_50702111163_xxx
    m = re.search(r"sample_(\d+)_", s, flags=re.IGNORECASE)
    if m:
        return m.group(1)

    # Case 4: embedded patterns like sample_PT495
    m = re.search(r"sample_PT[_-]?(\d+)", s, flags=re.IGNORECASE)
    if m:
        return f"PT{m.group(1)}"

    return None


def load_and_clean_metadata(metadata_path, id_col="ID"):
    meta = pd.read_csv(metadata_path, skipinitialspace=True)
    meta.columns = meta.columns.str.strip()

    if id_col not in meta.columns:
        raise ValueError(f"Column '{id_col}' not found in metadata file: {metadata_path}")

    meta[id_col] = meta[id_col].apply(normalize_id)
    meta = meta.dropna(subset=[id_col]).drop_duplicates(subset=[id_col], keep="first").copy()

    return meta


def extract_matching_sample_files(zip_path, output_dir, valid_ids):
    if os.path.exists(output_dir):
        shutil.rmtree(output_dir)
    os.makedirs(output_dir, exist_ok=True)

    seen_files = set()

    with zipfile.ZipFile(zip_path, "r") as z:
        for member in z.namelist():

            base = os.path.basename(member)

            if not base:
                continue
            if member.startswith("__MACOSX/") or base.startswith("._"):
                continue
            if not base.lower().endswith(".csv"):
                continue


            file_id = normalize_id(base)
            if file_id is None or file_id not in valid_ids:
                continue

            out_path = os.path.join(output_dir, f"{file_id}.csv")
            with z.open(member) as src, open(out_path, "wb") as dst:
                shutil.copyfileobj(src, dst)

            seen_files.add(file_id)

    return seen_files


def prepare_metadata_and_samples(
    zip_path="/content/sample_files.zip",
    metadata_path="/content/metadata.csv",
    output_dir="/content/samples",
    clean_metadata_path="/content/metadata.csv",
    id_col="ID",
):
    meta = load_and_clean_metadata(metadata_path, id_col=id_col)
    seen_files = extract_matching_sample_files(zip_path, output_dir, set(meta[id_col]))
    meta_clean = meta[meta[id_col].isin(seen_files)].copy()

    # Intentional overwrite
    meta_clean.to_csv(clean_metadata_path, index=False)

    print(f"Done. Renamed files are in: {output_dir}")
    print(f"Clean metadata saved to: {clean_metadata_path}")
    print(f"Number of matched files: {len(seen_files)}")

    return meta_clean, seen_files

